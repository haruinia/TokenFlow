import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {copyFile,mkdir,readFile,writeFile,chmod} from 'node:fs/promises';
import {resolve,join} from 'node:path';
const argument=name=>{const i=process.argv.indexOf(name);return i<0?undefined:process.argv[i+1];};
const source=argument('--source');assert.ok(source,'Pass --source with the pinned, patched Codex checkout');
assert.equal(process.platform,'darwin','This runtime is currently validated on macOS');
const pin=JSON.parse(await readFile('native/codex-agent-runtime.json','utf8'));
const run=(file,args,cwd=process.cwd())=>execFileSync(file,args,{cwd,encoding:'utf8',stdio:['ignore','pipe','inherit']}).trim();
assert.equal(run('git',['rev-parse','HEAD'],source),pin.sourceCommit,'Unexpected Codex source revision');
const patch=await readFile('native/codex-agent-runtime.patch');
assert.equal(run('git',['diff'],source),patch.toString().trim(),'Apply exactly native/codex-agent-runtime.patch to the pinned source');
if(!argument('--prebuilt'))execFileSync('cargo',['build','--locked','--release','-p','codex-app-server','--bin','codex-app-server'],{cwd:join(source,'codex-rs'),stdio:'inherit'});
const engine=argument('--prebuilt')??join(source,'codex-rs/target/release/codex-app-server');
const directory=resolve('sidecars',`${process.platform}-${process.arch}`,'codex-native-agents');await mkdir(directory,{recursive:true});
const binary=join(directory,'codex-app-server');await copyFile(engine,binary);await chmod(binary,0o755);
run('/usr/bin/strip',['-x',binary]);run('/usr/bin/codesign',['--force','--sign','-',binary]);
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const sha256=hash(await readFile(binary)),patchSha256=hash(patch),revision=hash(JSON.stringify({...pin,sha256,patchSha256}));
await writeFile(join(directory,'manifest.json'),JSON.stringify({format:1,revision,...pin,patchSha256,sha256,platform:process.platform,arch:process.arch},null,2)+'\n');
console.log(JSON.stringify({directory,revision,clientVersion:pin.clientVersion}));
